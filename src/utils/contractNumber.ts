import type { Deal } from '@/types'

/**
 * Номер договора в PDF — тот же, что у сделки в кабинете (#123).
 *
 * Раньше в договор, квитанцию и сводку шли первые 8 символов внутреннего id
 * («3F2A9C1B») — номер, который нигде в кабинете не видно и по которому
 * сделку не найти. Номер сделки уникален в кабинете партнёра, а при переносе
 * из Excel совпадает с номером договора из файла.
 *
 * Запасной вариант — для объекта сделки без номера (не должен встречаться).
 */
export function contractNumberOf(deal: Pick<Deal, 'id' | 'dealNumber'>): string {
  return deal.dealNumber ? String(deal.dealNumber) : deal.id.slice(0, 8).toUpperCase()
}
