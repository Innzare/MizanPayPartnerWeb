export const LOCKED_TEXT: Record<string, { title: string; note: string }> = {
  pendingIn: { title: 'Пришло без назначения', note: 'Пока не решили, чьи это деньги, распоряжаться ими нельзя.' },
}
/** Подпись строки с учётом её знака. */
export function stepText(st: AvailableStep, locked = false): { title: string; note: string } {
  const t = (locked ? LOCKED_TEXT[st.key] : undefined) ?? STEP_TEXT[st.key]
  if (!t) return { title: st.key, note: '' }
  const minus = (t as { minus?: { title: string; note: string } }).minus
  return st.sign === '-' && minus ? minus : { title: t.title, note: t.note }
}

